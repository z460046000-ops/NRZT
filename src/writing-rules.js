/** 单章重试也使用相同的章节任务，避免整稿与补章口径不同。 */
export function chapterWritingRule(item) {
  const topics = new Set(item?.topics ?? [])
  if (topics.has('trends') || topics.has('context')) return '本章解释有来源的环境变化或业务背景、变化对目标客户的具体影响，以及为什么需要本方案；趋势要标明来源和时间，不能用行业常识或样本措辞冒充新证据。若本章是开篇，先用资料支撑的一句话介绍产品定位，再进入环境变化；不以“AI 正在重构”之类抽象判断开场。'
  if (topics.has('problem_solution')) {
    if (/挑战|痛点|困境|现状|问题/u.test(item?.heading ?? '') && !/方案|做法|应对/u.test(item?.heading ?? '')) {
      return '这是痛点讲解章。只讲有依据的问题，不在这里铺开产品方案。每个问题分别写可识别的短标题、工作中真实可见的场景与动作、造成的麻烦或经营影响；同一问题的几个层次可以分块讲清，优先 3—5 个有依据的块。章节大标题、问题小标题和正文各司其职，别用一整段抽象结论代替分析。四类挑战只是参考组织法，数量与名称由本轮材料决定。'
    }
    return '若本章同时包含问题与做法，先用短语概括有依据的问题，再把主要篇幅用于对应的产品做法、使用者动作和可见结果；不要重复一整章痛点描述。'
  }
  if (topics.has('architecture') || topics.has('capabilities')) return '这是解决方案或能力讲解章。先用短语回扣前面的具体痛点，再把主要篇幅用于产品或方案是什么、谁使用、在哪一步做什么、怎样回应问题、留下什么可见结果；不同平台的职责和能力边界要写清。不能把“围绕某某形成持续运营”当成产品定义。'
  if (topics.has('implementation') || topics.has('service')) return '本章说明启动条件、实施步骤、交付物和服务范围；没有合同依据时不承诺具体时限或结果。'
  if (topics.has('company')) return '本章只写有来源的公司背景、业务与资质，说明它们与本方案交付的关系。'
  return '本章要让陌生读者从标题、导语和正文理解对象、动作及价值，避免抽象短语堆叠。'
}
