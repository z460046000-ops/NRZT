/** 单章重试也使用相同的章节任务，避免整稿与补章口径不同。 */
export function chapterWritingRule(item) {
  const topics = new Set(item?.topics ?? [])
  if (topics.has('trends') || topics.has('context')) return '本章解释有来源的环境变化或业务背景、变化对目标客户的具体影响，以及为什么需要本方案；趋势要标明来源和时间，不能用行业常识或样本措辞冒充新证据。'
  if (topics.has('problem_solution')) return '本章先说明目标客户的典型或已确认挑战：每项有可识别的问题名、具体表现、业务影响；随后指出一一对应的产品做法和作用环节。四类挑战只是参考组织法，数量与名称由本轮材料决定。'
  if (topics.has('architecture') || topics.has('capabilities')) return '本章先用一句话说明方案或产品是什么，再按业务动作说明能力怎样解决前述问题；不同平台的职责和能力边界要写清。'
  if (topics.has('implementation') || topics.has('service')) return '本章说明启动条件、实施步骤、交付物和服务范围；没有合同依据时不承诺具体时限或结果。'
  if (topics.has('company')) return '本章只写有来源的公司背景、业务与资质，说明它们与本方案交付的关系。'
  return '本章要让陌生读者从标题、导语和正文理解对象、动作及价值，避免抽象短语堆叠。'
}
